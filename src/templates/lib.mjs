import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const manifest = JSON.parse(readFileSync(path.join(root, 'media', 'manifest.json'), 'utf8'));

export const html = String.raw;

export function esc(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

export const join = (list, fn) => list.map(fn).join('');

export function media(key) {
  const m = manifest[key];
  if (!m) throw new Error(`Imagem não encontrada no manifest: ${key}`);
  return m;
}

export function srcFor(key, width) {
  const m = media(key);
  if (m.single) return `/img/${m.dir}/${m.single}`;
  const w = width ? m.widths.filter((x) => x <= width).pop() || m.widths[0] : m.widths[m.widths.length - 1];
  return `/img/${m.dir}/${key}-${w}.webp`;
}

/**
 * <picture> com AVIF + WebP, srcset por largura, width/height para evitar
 * deslocamento de layout e carregamento preguiçoso por padrão.
 */
export function picture(key, { alt = '', sizes = '100vw', cls = '', imgCls = '', eager = false, priority = false, style = '' } = {}) {
  const m = media(key);
  if (m.single) {
    return `<img src="/img/${m.dir}/${m.single}" alt="${esc(alt)}" width="${m.w}" height="${m.h}"${cls ? ` class="${cls}"` : ''} loading="${eager ? 'eager' : 'lazy'}" decoding="async">`;
  }
  const set = (ext) => m.widths.map((w) => `/img/${m.dir}/${key}-${w}.${ext} ${w}w`).join(', ');
  const largest = m.widths[m.widths.length - 1];
  const h = Math.round((m.h * largest) / m.w);
  const loading = eager || priority ? 'eager' : 'lazy';
  return (
    `<picture${cls ? ` class="${cls}"` : ''}>` +
    `<source type="image/avif" srcset="${set('avif')}" sizes="${sizes}">` +
    `<source type="image/webp" srcset="${set('webp')}" sizes="${sizes}">` +
    `<img src="/img/${m.dir}/${key}-${largest}.webp" alt="${esc(alt)}" width="${largest}" height="${h}"` +
    `${imgCls ? ` class="${imgCls}"` : ''}${style ? ` style="${style}"` : ''} loading="${loading}" decoding="${priority ? 'sync' : 'async'}"` +
    `${priority ? ' fetchpriority="high"' : ''}></picture>`
  );
}

/** Link de pré-carregamento da imagem principal (LCP). */
export function preloadImage(key, sizes = '100vw') {
  const m = media(key);
  const set = m.widths.map((w) => `/img/${m.dir}/${key}-${w}.avif ${w}w`).join(', ');
  return `<link rel="preload" as="image" type="image/avif" imagesrcset="${set}" imagesizes="${sizes}" fetchpriority="high">`;
}

